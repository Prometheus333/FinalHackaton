# Live stream (SSE) + background poller
# --------------------------------------------------------------------------
_subscribers: list[queue.Queue] = []
_subs_lock = threading.Lock()
_tracked: set[str] = set(DEFAULT_SYMBOLS)
_last_sent: dict[str, float] = {}


def _broadcast(event: str, payload: dict):
    msg = f"event: {event}\ndata: {json.dumps(payload)}\n\n"
    with _subs_lock:
        for q in list(_subscribers):
            try:
                q.put_nowait(msg)
            except queue.Full:
                pass


def _poller():
    while True:
        try:
            with _subs_lock:
                active = bool(_subscribers)
            if active and _tracked:
                snaps = get_snapshots(sorted(_tracked))
                changed = {
                    s: v for s, v in snaps.items()
                    if _last_sent.get(s) != v["price"]
                }
                if changed:
                    _last_sent.update({s: v["price"] for s, v in changed.items()})
                    _broadcast("quotes", {"quotes": list(changed.values()),
                                          "ts": datetime.now(timezone.utc).isoformat()})
        except Exception as exc:  # noqa: BLE001
            app.logger.warning("poller: %s", exc)
        time.sleep(POLL_SECONDS)


threading.Thread(target=_poller, daemon=True).start()


@app.route("/api/stream")
def api_stream():
    symbols = request.args.get("symbols", ",".join(DEFAULT_SYMBOLS))
    _tracked.update(s.strip().upper() for s in symbols.split(",") if s.strip())
    q: queue.Queue = queue.Queue(maxsize=50)
    with _subs_lock:
        _subscribers.append(q)

    @stream_with_context
    def gen():
        try:
            yield "retry: 3000\n\n"
            snaps = get_snapshots(sorted(_tracked))
            yield f"event: quotes\ndata: {json.dumps({'quotes': list(snaps.values())})}\n\n"
            while True:
                try:
                    yield q.get(timeout=15)
                except queue.Empty:
                    yield ": keepalive\n\n"
        finally:
            with _subs_lock:
                if q in _subscribers:
                    _subscribers.remove(q)

    return Response(gen(), mimetype="text/event-stream",
                    headers={"Cache-Control": "no-cache", "X-Accel-Buffering": "no"})


