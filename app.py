def build_simulation(amount: float, symbols: list[str]) -> dict:
    """Allocates capital by inverse volatility and projects it forward.

    Inverse-vol weighting means calmer assets get more money, which is the
    standard naive risk-parity approach. Returns are drawn from each symbol's
    own history and hard-capped: extrapolating a hot streak for ten years is
    how simulators end up lying.
    """
    stats = {}
    for sym in symbols[:10]:
        a = compute_analysis(sym)
        bars = a.pop("_bars", [])
        if a.get("error") or len(bars) < 60:
            continue
        closes = [b["close"] for b in bars]
        years = len(closes) / 252
        cagr = ((closes[-1] / closes[0]) ** (1 / years) - 1) if years > 0.5 and closes[0] else 0.0
        cagr = max(min(cagr, 0.25), -0.15)          # sanity cap
        vol = (a.get("annualized_vol_pct") or 25) / 100
        stats[sym] = {"price": a["last_close"], "cagr": cagr, "vol": max(vol, 0.05),
                      "source": a.get("data_source")}

    if not stats:
        return {"error": "no usable price history for these symbols"}

    inv = {s: 1 / v["vol"] for s, v in stats.items()}
    tot = sum(inv.values())
    alloc = []
    for sym, v in stats.items():
        w = inv[sym] / tot
        cash = amount * w
        alloc.append({
            "symbol": sym, "weight_pct": round(w * 100, 1),
            "amount": round(cash, 2), "price": v["price"],
            "shares": round(cash / v["price"], 2),
            "assumed_cagr_pct": round(v["cagr"] * 100, 1),
            "annualized_vol_pct": round(v["vol"] * 100, 1),
        })

    port_cagr = sum(stats[a["symbol"]]["cagr"] * a["weight_pct"] / 100 for a in alloc)
    port_vol = math.sqrt(sum((a["weight_pct"] / 100) ** 2 *
                             stats[a["symbol"]]["vol"] ** 2 for a in alloc))
    # Correlation is unknown, so widen the band: independence would understate risk.
    port_vol = min(port_vol * 1.6, 0.45)

    horizons = []
    for yrs in (2, 5, 10):
        median = amount * ((1 + port_cagr) ** yrs)
        spread = port_vol * math.sqrt(yrs)
        horizons.append({
            "years": yrs,
            "median": round(median, 2),
            "low": round(median * math.exp(-spread), 2),
            "high": round(median * math.exp(spread), 2),
            "total_return_pct": round((median / amount - 1) * 100, 1),
        })

    return {
        "invested": round(amount, 2),
        "allocation": alloc,
        "method": "inverse volatility weighting",
        "portfolio_cagr_pct": round(port_cagr * 100, 2),
        "portfolio_vol_pct": round(port_vol * 100, 1),
        "horizons": horizons,
        "diversification": build_diversification(list(stats.keys())),
        "caveat": ("Past drift projected forward with a volatility band. Not a "
                   "forecast: real returns depend on events no model has seen."),
    }


