# Projections — deterministic, computed in Python
# --------------------------------------------------------------------------
def build_projection(
    bars: list[dict], days: int = 10, scenario: str = "base", shock_pct: float = 0.0
) -> list[dict]:
    """Projected path from the REAL drift and volatility.

    'bull'/'bear' = base drift ± daily sigma. The initial shock models what-ifs
    ("what if it drops 10% on an earnings miss?").
    """
    if not bars:
        return []
    closes = [b["close"] for b in bars]
    rets = [closes[i] / closes[i - 1] - 1 for i in range(1, len(closes)) if closes[i - 1]][-60:]
    mu = sum(rets) / len(rets) if rets else 0.0
    sd = (
        math.sqrt(sum((r - mu) ** 2 for r in rets) / len(rets)) if len(rets) > 1 else 0.01
    )
    drift = {"base": mu, "bull": mu + sd * 0.6, "bear": mu - sd * 0.6}.get(scenario, mu)
    drift = max(min(drift, 0.02), -0.02)  # sanity cap

    try:
        last_date = datetime.fromisoformat(bars[-1]["time"][:10])
    except Exception:  # noqa: BLE001
        last_date = datetime.now()

    price = closes[-1] * (1 + shock_pct / 100.0)
    pts, added = [], 0
    i = 1
    while added < days and i < days * 3:
        d = last_date + timedelta(days=i)
        i += 1
        if d.weekday() >= 5:  # skip weekends: the chart used to break
            continue
        price *= 1 + drift
        pts.append({"time": d.date().isoformat(), "value": round(price, 2)})
        added += 1
    return pts


