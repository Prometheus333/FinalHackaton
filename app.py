# Instrument search (Alpaca /v2/assets)
# --------------------------------------------------------------------------
# Alpaca has no search endpoint: the universe is downloaded once (~11k assets)
# and matched locally. Instant, and works offline.
_assets: list[dict] = []
_assets_lock = threading.Lock()


def load_assets(force: bool = False) -> list[dict]:
    global _assets
    with _assets_lock:
        if _assets and not force:
            return _assets
    try:
        r = _alpaca.get(
            f"{ALPACA_TRADING_URL}/assets",
            params={"status": "active", "asset_class": "us_equity"},
            timeout=25,
        )
        r.raise_for_status()
        data = [
            {
                "symbol": a["symbol"],
                "name": a.get("name") or a["symbol"],
                "exchange": a.get("exchange"),
                "etf": bool(a.get("attributes") and "etf" in str(a.get("attributes")).lower()),
                "tradable": a.get("tradable", False),
            }
            for a in r.json()
            if a.get("tradable") and a.get("exchange") in ("NASDAQ", "NYSE", "ARCA", "AMEX", "BATS")
        ]
        with _assets_lock:
            _assets = data
        app.logger.info("Alpaca universe loaded: %d assets", len(data))
    except Exception as exc:  # noqa: BLE001
        if "401" in str(exc):
            app.logger.error(
                "/assets returned 401: your Alpaca keys are empty or not valid for %s. "
                "Check ALPACA_KEY_ID / ALPACA_SECRET_KEY in your .env "
                "(current key starts with %r).",
                ALPACA_TRADING_URL,
                (ALPACA_KEY_ID[:4] + "…") if ALPACA_KEY_ID else "EMPTY",
            )
        else:
            app.logger.warning("Could not load /assets: %s", exc)
    return _assets


def search_assets(query: str, limit: int = 8) -> list[dict]:
    """Ranking: exact ticker > ticker starts with > name starts with > name
    contains. So 'apple' returns AAPL and 'micro' puts MSFT on top."""
    q = (query or "").strip().upper()
    if not q:
        return []
    assets = load_assets()
    if not assets:
        # With no universe (401 or network down) we still accept exact tickers:
        # search loses name matching, but the app keeps working.
        snap = get_snapshots([q]).get(q)
        if snap and snap.get("source") == "alpaca":
            return [{"symbol": q, "name": q, "exchange": "?", "etf": False, "tradable": True}]
        return []
    scored = []
    for a in assets:
        sym, name = a["symbol"], a["name"].upper()
        if sym == q:
            s = 0
        elif sym.startswith(q):
            s = 1
        elif name.startswith(q):
            s = 2
        elif q in name:
            s = 3
        elif q in sym:
            s = 4
        else:
            continue
        scored.append((s, len(sym), a))
    scored.sort(key=lambda x: (x[0], x[1]))
    return [a for _, _, a in scored[:limit]]


