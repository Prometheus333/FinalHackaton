# Indicators — computed in Python, NOT by the LLM
# --------------------------------------------------------------------------
def _sma(v: list[float], n: int):
    return round(sum(v[-n:]) / n, 2) if len(v) >= n else None


def _ema(v: list[float], n: int):
    if len(v) < n:
        return None
    k, e = 2 / (n + 1), sum(v[:n]) / n
    for x in v[n:]:
        e = x * k + e * (1 - k)
    return round(e, 2)


def _rsi(v: list[float], n: int = 14):
    if len(v) < n + 1:
        return None
    gains = losses = 0.0
    for i in range(-n, 0):
        d = v[i] - v[i - 1]
        gains += max(d, 0)
        losses += max(-d, 0)
    if losses == 0:
        return 100.0
    rs = (gains / n) / (losses / n)
    return round(100 - 100 / (1 + rs), 1)


def _atr_pct(bars: list[dict], n: int = 14):
    if len(bars) < n + 1:
        return None
    trs = []
    for i in range(-n, 0):
        h, l, pc = bars[i]["high"], bars[i]["low"], bars[i - 1]["close"]
        trs.append(max(h - l, abs(h - pc), abs(l - pc)))
    atr = sum(trs) / n
    return round(atr / bars[-1]["close"] * 100, 2)


def compute_analysis(symbol: str, timeframe: str = "1Day") -> dict:
    """Only fields with an actual value are returned.

    Anything the data does not support is omitted entirely rather than sent as
    null: an empty slot in the UI and a null in the prompt both invite the model
    to talk about something it does not know.
    """
    payload = get_bars(symbol, timeframe=timeframe, limit=250)
    bars = payload["bars"]
    closes = [b["close"] for b in bars]
    if not closes:
        return {"symbol": symbol, "error": "no data"}

    def pct(n: int):
        if len(closes) <= n or not closes[-n - 1]:
            return None
        return round((closes[-1] / closes[-n - 1] - 1) * 100, 2)

    rets = [
        closes[i] / closes[i - 1] - 1
        for i in range(max(1, len(closes) - 60), len(closes))
        if closes[i - 1]
    ]
    mean = sum(rets) / len(rets) if rets else 0.0
    var = sum((r - mean) ** 2 for r in rets) / len(rets) if rets else 0.0
    daily_vol = math.sqrt(var)

    window = closes[-252:]
    hi, lo = max(window), min(window)
    sma20, sma50 = _sma(closes, 20), _sma(closes, 50)

    changes = {k: v for k, v in
               {"1d": pct(1), "5d": pct(5), "20d": pct(20), "60d": pct(60)}.items()
               if v is not None}

    vols = [b["volume"] for b in bars[-20:] if b.get("volume")]
    rel_vol = (round(bars[-1]["volume"] / (sum(vols) / len(vols)), 2)
               if len(vols) == 20 and bars[-1].get("volume") else None)

    out = {
        "symbol": symbol,
        "timeframe": timeframe,
        "data_source": payload["source"],
        "as_of": bars[-1]["time"],
        "bars_available": len(bars),
        "last_close": closes[-1],
    }
    if payload.get("feed"):
        out["feed"] = payload["feed"]
    if payload.get("stale"):
        out["stale"] = True
        if payload.get("age_days") is not None:
            out["days_since_last_bar"] = payload["age_days"]
    if changes:
        out["change_pct"] = changes
    if sma20:
        out["sma20"] = sma20
        out["price_vs_sma20_pct"] = round((closes[-1] / sma20 - 1) * 100, 2)
    if sma50:
        out["sma50"] = sma50
    if sma20 and sma50:
        out["trend"] = "uptrend" if sma20 > sma50 else "downtrend"
    if (ema := _ema(closes, 12)) is not None:
        out["ema12"] = ema
    if (rsi := _rsi(closes)) is not None:
        out["rsi14"] = rsi
    if (atr := _atr_pct(bars)) is not None:
        out["atr14_pct"] = atr
    if rets:
        out["annualized_vol_pct"] = round(daily_vol * math.sqrt(252) * 100, 1)
        out["daily_vol_pct"] = round(daily_vol * 100, 2)
    if hi > lo:
        out["range_52w"] = {"high": round(hi, 2), "low": round(lo, 2)}
        out["pos_in_52w_range_pct"] = round((closes[-1] - lo) / (hi - lo) * 100, 1)
    if rel_vol is not None:
        out["relative_volume"] = rel_vol

    out["_bars"] = bars
    return out


