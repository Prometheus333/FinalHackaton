# Recommendation engine — combines chart signals with news tone
# --------------------------------------------------------------------------
POS_WORDS = ("beat", "beats", "surge", "surges", "rally", "rallies", "upgrade",
             "upgraded", "record", "jumps", "soars", "growth", "profit", "wins",
             "raises", "outperform", "bullish", "strong", "gains", "approval")
NEG_WORDS = ("miss", "misses", "plunge", "plunges", "slump", "downgrade", "cut",
             "cuts", "probe", "lawsuit", "recall", "warns", "warning", "falls",
             "drops", "layoff", "layoffs", "bearish", "weak", "loss", "losses",
             "investigation", "delay", "delays")


def news_tone(items: list[dict]) -> dict:
    """Crude but transparent headline scoring. Deliberately not an LLM call:
    it must be fast, free and reproducible."""
    pos = neg = 0
    drivers = []
    for it in items[:10]:
        t = (it.get("title") or "").lower()
        p = sum(1 for w in POS_WORDS if w in t)
        n = sum(1 for w in NEG_WORDS if w in t)
        if p > n:
            pos += 1
            drivers.append({"tone": "+", "title": it.get("title", "")[:110]})
        elif n > p:
            neg += 1
            drivers.append({"tone": "-", "title": it.get("title", "")[:110]})
    total = pos + neg
    if not total:
        label = "neutral"
    elif pos >= neg * 2:
        label = "positive"
    elif neg >= pos * 2:
        label = "negative"
    else:
        label = "mixed"
    return {"label": label, "positive": pos, "negative": neg,
            "drivers": drivers[:3], "headlines_scored": len(items[:10])}


def build_recommendation(symbol: str) -> dict:
    """Turns indicators + headlines into an explicit, auditable read.

    Every point of conviction traces back to a rule listed in `signals`, so the
    model never has to invent a rationale — it just reads this out.
    """
    a = compute_analysis(symbol)
    if a.get("error"):
        return {"symbol": symbol, "error": a["error"]}
    a.pop("_bars", None)

    price = a["last_close"]
    atr = a.get("atr14_pct")
    rsi = a.get("rsi14")
    signals, score = [], 0

    if a.get("trend") == "uptrend":
        score += 2
        signals.append("SMA20 above SMA50")
    elif a.get("trend") == "downtrend":
        score -= 2
        signals.append("SMA20 below SMA50")

    dev = a.get("price_vs_sma20_pct")
    if dev is not None:
        if dev > 0:
            score += 1
            signals.append(f"{dev}% above the 20-day")
        else:
            score -= 1
            signals.append(f"{abs(dev)}% below the 20-day")

    if rsi is not None:
        if rsi > 70:
            score -= 2
            signals.append(f"RSI {rsi}, overbought")
        elif rsi < 30:
            score += 2
            signals.append(f"RSI {rsi}, oversold")
        elif rsi > 55:
            score += 1
            signals.append(f"RSI {rsi}, momentum positive")
        elif rsi < 45:
            score -= 1
            signals.append(f"RSI {rsi}, momentum negative")

    pos52 = a.get("pos_in_52w_range_pct")
    if pos52 is not None:
        if pos52 > 90:
            score -= 1
            signals.append(f"{pos52}% of the 52-week range, near highs")
        elif pos52 < 15:
            score += 1
            signals.append(f"{pos52}% of the 52-week range, near lows")

    tone = news_tone(get_news(symbol, 10))
    score += {"positive": 2, "negative": -2, "mixed": 0, "neutral": 0}[tone["label"]]
    if tone["label"] in ("positive", "negative"):
        signals.append(f"headline tone {tone['label']}")

    if score >= 4:
        bias, conviction = "bullish", "high"
    elif score >= 2:
        bias, conviction = "bullish", "moderate"
    elif score <= -4:
        bias, conviction = "bearish", "high"
    elif score <= -2:
        bias, conviction = "bearish", "moderate"
    else:
        bias, conviction = "neutral", "low"

    rec = {
        "symbol": symbol,
        "as_of": a.get("as_of"),
        "data_source": a.get("data_source"),
        "price": price,
        "bias": bias,
        "conviction": conviction,
        "score": score,
        "signals": signals,
        "news_tone": tone["label"],
        "news_drivers": tone["drivers"],
    }
    if a.get("stale"):
        rec["stale"] = True
    # Levels sized off real volatility, not round numbers.
    # Explicit, actionable levels. HOLD when conviction does not justify a trade:
    # a recommendation engine that always has a trade is a broken one.
    rec["action"] = "HOLD"
    if atr:
        rec["atr_pct"] = atr
        band = price * atr / 100
        if bias == "bullish" and conviction in ("moderate", "high"):
            rec["action"] = "BUY"
            rec["buy_point"] = round(price - band * 0.25, 2)   # slight pullback entry
            rec["stop_loss"] = round(price - band * 1.5, 2)
            rec["sell_point"] = round(price + band * 3.0, 2)
            rec["risk_reward"] = round((band * 3.0) / (band * 1.5), 2)
        elif bias == "bearish" and conviction in ("moderate", "high"):
            rec["action"] = "SELL"
            rec["sell_point"] = round(price + band * 0.25, 2)  # bounce to exit into
            rec["stop_loss"] = round(price + band * 1.5, 2)
            rec["buy_point"] = round(price - band * 3.0, 2)    # where it becomes interesting again
            rec["risk_reward"] = round((band * 3.0) / (band * 1.5), 2)
        else:
            rec["hold_reason"] = (
                f"signals conflict (score {score}); no edge worth the {atr}% daily range"
            )
            rec["revisit_above"] = round(price + band * 2, 2)
            rec["revisit_below"] = round(price - band * 2, 2)
    else:
        rec["hold_reason"] = "not enough history to size levels"
    return rec


