def get_news(symbol: str | None = None, limit: int = 12) -> list[dict]:
    key = f"news:{symbol or 'market'}"
    if (hit := cache_get(key)) is not None:
        return hit
    sym = symbol or "%5EGSPC"
    url = f"https://feeds.finance.yahoo.com/rss/2.0/headline?s={sym}&region=US&lang=en-US"
    items = []
    try:
        for e in feedparser.parse(url).entries[:limit]:
            items.append(
                {
                    "title": e.get("title", ""),
                    "link": e.get("link", ""),
                    "published": e.get("published", ""),
                    "summary": re.sub("<[^<]+?>", "", e.get("summary", ""))[:220],
                    "source": "Yahoo Finance",
                }
            )
    except Exception as exc:  # noqa: BLE001
        app.logger.warning("News fetch failed: %s", exc)
    if not items:
        items = [{"title": f"No headlines available for {symbol or 'the market'}.", "link": "",
                  "published": "", "summary": "", "source": "system"}]
    cache_set(key, items, TTL["news"])
    return items


def filter_news_by_keywords(items, keywords):
    if not keywords:
        return items
    kw = [k.lower() for k in keywords]
    f = [i for i in items if any(k in (i["title"] + " " + i["summary"]).lower() for k in kw)]
    return f or items


