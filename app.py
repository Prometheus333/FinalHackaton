def get_news_by_topic(topic: str, limit: int = 12) -> list[dict]:
    key = f"news:topic:{topic.lower()}"
    if (hit := cache_get(key)) is not None:
        return hit
    from urllib.parse import quote_plus

    url = (
        "https://news.google.com/rss/search?q="
        + quote_plus(f"{topic} stock market finance")
        + "&hl=en-US&gl=US&ceid=US:en"
    )
    items = []
    try:
        for e in feedparser.parse(url).entries[:limit]:
            items.append(
                {
                    "title": e.get("title", ""),
                    "link": e.get("link", ""),
                    "published": e.get("published", ""),
                    "summary": re.sub("<[^<]+?>", "", e.get("summary", ""))[:220],
                    "source": (e.get("source", {}) or {}).get("title", "Google News"),
                    "topic": topic,
                }
            )
    except Exception as exc:  # noqa: BLE001
        app.logger.warning("Topic news fetch failed: %s", exc)
    if items:
        cache_set(key, items, TTL["news"])
    return items


def extract_article(url: str) -> dict:
    """Best-effort article body extraction, so the agent can explain it by voice
    instead of just reading the headline."""
    key = f"art:{url}"
    if (hit := cache_get(key)) is not None:
        return hit
    out = {"url": url, "text": "", "title": ""}
    try:
        r = requests.get(
            url,
            timeout=10,
            verify=VERIFY_SSL,
            headers={"User-Agent": "Mozilla/5.0 (compatible; TradingTerminal/1.0)"},
        )
        html = r.text
        m = re.search(r"<title[^>]*>(.*?)</title>", html, re.S | re.I)
        out["title"] = re.sub(r"\s+", " ", m.group(1)).strip() if m else ""
        body = re.sub(r"(?s)<(script|style|nav|footer|header|aside)[^>]*>.*?</\1>", " ", html)
        paras = re.findall(r"(?s)<p[^>]*>(.*?)</p>", body)
        text = " ".join(re.sub("<[^>]+>", "", p) for p in paras)
        text = re.sub(r"&[a-z]+;", " ", text)
        out["text"] = re.sub(r"\s+", " ", text).strip()[:4000]
    except Exception as exc:  # noqa: BLE001
        out["error"] = str(exc)[:150]
    cache_set(key, out, 900)
    return out


