def _extract_json(text: str):
    text = re.sub(r"^```(json)?|```$", "", text.strip()).strip()
    try:
        return json.loads(text)
    except Exception:  # noqa: BLE001
        m = re.search(r"\{.*\}", text, re.DOTALL)
        if m:
            try:
                return json.loads(m.group(0))
            except Exception:  # noqa: BLE001
                return None
    return None


def ask_ai(message: str, symbol: str, session_id: str = "default") -> dict:
    t0 = time.time()

    # Context in parallel: analysis + news at once, not sequentially.
    f_analysis = _pool.submit(compute_analysis, symbol)
    f_news = _pool.submit(get_news, symbol, 6)
    f_rec = _pool.submit(build_recommendation, symbol)
    f_brief = _pool.submit(build_briefing, sorted(_tracked)[:6])
    analysis = f_analysis.result()
    bars = analysis.pop("_bars", [])
    headlines = [n["title"] for n in f_news.result()[:5]]

    rec = f_rec.result()
    rec.pop("as_of", None)
    ctx = {**analysis, "recent_headlines": headlines,
           "recommendation": {k: v for k, v in rec.items() if k not in ("symbol",)},
           "watchlist_scan": f_brief.result().get("alerts", [])}
    hist = _history(session_id)

    messages = [{"role": "system", "content": SYSTEM_PROMPT}]
    messages += list(hist)
    messages.append(
        {
            "role": "user",
            "content": f"METRICS ({symbol}):\n{json.dumps(ctx, ensure_ascii=False)}\n\nUser: {message}",
        }
    )

    parsed = None
    try:
        completion = llm_client().chat.completions.create(
            model=LLM_MODEL,
            messages=messages,
            temperature=0.1,          # was 0.4: structured output kept breaking
            max_tokens=300,
            response_format={"type": "json_object"},
        )
        parsed = _extract_json(completion.choices[0].message.content or "")
    except Exception as exc:  # noqa: BLE001
        app.logger.warning("LLM call failed: %s", exc)

    if not parsed or "reply" not in parsed:
        parsed = _fallback(analysis, message)

    # The server materializes commands: the model never generates prices.
    commands = []
    for c in parsed.get("commands", [])[:4]:
        a = c.get("action")
        if a in ("add_projection", "add_scenario"):
            pts = build_projection(
                bars,
                days=int(c.get("days") or 10),
                scenario=str(c.get("scenario") or "base"),
                shock_pct=float(c.get("shock_pct") or 0),
            )
            if pts:
                commands.append(
                    {"action": a, "symbol": symbol, "label": c.get("label") or "AI Projection",
                     "points": pts}
                )
        elif a == "search_symbol":
            hits = search_assets(c.get("query", ""), 5)
            if hits:
                commands.append({"action": "search_results", "query": c.get("query"),
                                 "results": hits})
        elif a in ("add_overlay", "remove_overlay", "set_symbol", "filter_news",
                   "clear_projections", "load_news", "open_news",
                   "add_watchlist", "remove_watchlist", "focus_panel",
                   "toggle_indicator"):
            commands.append(c)

    hist.append({"role": "user", "content": message[:400]})
    hist.append({"role": "assistant", "content": parsed["reply"][:400]})

    return {
        "reply": parsed["reply"],
        "commands": commands,
        "metrics": {k: v for k, v in analysis.items() if not k.startswith("_")},
        "latency_ms": int((time.time() - t0) * 1000),
    }


def _fallback(a: dict, message: str) -> dict:
    """Deterministic answer when the LLM is unavailable: uses the same indicators,
    so the demo never looks broken."""
    if a.get("error"):
        return {"reply": f"No market data available for {a.get('symbol')}.", "commands": []}
    rsi = a.get("rsi14")
    tone = "overbought" if rsi and rsi > 70 else "oversold" if rsi and rsi < 30 else "neutral"
    scen = "bull" if a.get("trend") == "uptrend" else "bear"
    rsi = rsi if rsi is not None else "n/a"
    return {
        "reply": (
            f"{a['symbol']} at {a['last_close']}, RSI {rsi} ({tone}). "
            f"{scen.capitalize()} projection plotted."
        ),
        "commands": [{"action": "add_projection", "scenario": scen, "days": 10,
                      "label": f"{scen.capitalize()} projection"}],
    }


