def build_diversification(symbols: list[str]) -> dict:
    """Concentration read plus the single most useful gap to fill.

    Uses HHI (Herfindahl index) on equal-weighted buckets: with no position
    sizes available, every holding counts the same.
    """
    if not symbols:
        return {"score": 0, "verdict": "empty watchlist", "buckets": {}, "gaps": []}

    buckets: dict[str, int] = {}
    for s in symbols:
        buckets[classify(s)] = buckets.get(classify(s), 0) + 1

    n = len(symbols)
    hhi = sum((c / n) ** 2 for c in buckets.values())
    # HHI 1.0 = everything in one bucket; 1/k = perfectly spread over k buckets.
    score = round(max(0.0, min(1.0, (1 - hhi) / (1 - 1 / max(len(buckets), 2)))) * 100)

    if len(buckets) == 1:
        verdict = f"fully concentrated in {next(iter(buckets))}"
    elif score >= 70:
        verdict = f"well spread across {len(buckets)} groups"
    elif score >= 40:
        verdict = f"moderately concentrated across {len(buckets)} groups"
    else:
        verdict = f"heavily concentrated across {len(buckets)} groups"

    top = max(buckets.items(), key=lambda kv: kv[1])
    gaps = []
    if top[1] / n >= 0.5 and len(symbols) > 2:
        gaps.append({"issue": f"{round(top[1]/n*100)}% sits in {top[0]}",
                     "suggest": None,
                     "why": "One sector shock would move most of the list at once."})
    held = set(symbols)
    for label, family, pick, why in GAP_SUGGESTIONS:
        if not (held & family):
            gaps.append({"issue": f"no {label} exposure", "suggest": pick, "why": why})

    return {"score": score, "verdict": verdict, "buckets": buckets,
            "holdings": n, "gaps": gaps[:3]}


