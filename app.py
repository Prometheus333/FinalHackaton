def build_briefing(symbols: list[str]) -> dict:
    """Scans the watchlist and surfaces only what is worth interrupting for."""
    snaps = get_snapshots(symbols)
    alerts = []
    for sym in symbols[:8]:
        q = snaps.get(sym) or {}
        chg = q.get("change_pct")
        if chg is not None and abs(chg) >= 2:
            alerts.append({"symbol": sym, "kind": "move", "urgency": abs(chg),
                           "text": f"{sym} {'up' if chg > 0 else 'down'} {abs(chg)}% today"})
        a = compute_analysis(sym)
        a.pop("_bars", None)
        rsi = a.get("rsi14")
        if rsi is not None and (rsi > 72 or rsi < 28):
            alerts.append({"symbol": sym, "kind": "rsi", "urgency": abs(rsi - 50) / 10,
                           "text": f"{sym} RSI {rsi}, "
                                   f"{'overbought' if rsi > 72 else 'oversold'}"})
    alerts.sort(key=lambda x: -x["urgency"])
    return {"alerts": alerts[:3], "scanned": len(symbols),
            "quotes": [v for v in snaps.values()]}


