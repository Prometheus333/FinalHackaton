def indicator_series(bars: list[dict], which: str) -> dict:
    """Technical overlays computed in Python so the chart and the model always
    agree on the numbers. Returns {series: {name: [{time, value}]}, levels: []}.
    """
    if len(bars) < 25:
        return {"series": {}, "levels": []}
    closes = [b["close"] for b in bars]
    times = [b["time"] for b in bars]
    out: dict = {"series": {}, "levels": []}

    def rolling(fn, n):
        return [
            {"time": times[i], "value": round(fn(closes[i - n + 1 : i + 1]), 2)}
            for i in range(n - 1, len(closes))
        ]

    if which in ("sma20", "all"):
        out["series"]["sma20"] = rolling(lambda w: sum(w) / len(w), 20)
    if which in ("sma50", "all") and len(closes) >= 50:
        out["series"]["sma50"] = rolling(lambda w: sum(w) / len(w), 50)
    if which in ("ema12", "all"):
        k, e, pts = 2 / 13, sum(closes[:12]) / 12, []
        for i in range(12, len(closes)):
            e = closes[i] * k + e * (1 - k)
            pts.append({"time": times[i], "value": round(e, 2)})
        out["series"]["ema12"] = pts

    if which in ("bollinger", "all"):
        up, lo = [], []
        for i in range(19, len(closes)):
            w = closes[i - 19 : i + 1]
            m = sum(w) / 20
            sd = math.sqrt(sum((x - m) ** 2 for x in w) / 20)
            up.append({"time": times[i], "value": round(m + 2 * sd, 2)})
            lo.append({"time": times[i], "value": round(m - 2 * sd, 2)})
        out["series"]["bb_upper"], out["series"]["bb_lower"] = up, lo

    if which in ("vwap", "all"):
        cum_pv = cum_v = 0.0
        pts = []
        for b in bars[-60:]:
            tp = (b["high"] + b["low"] + b["close"]) / 3
            cum_pv += tp * (b["volume"] or 0)
            cum_v += b["volume"] or 0
            if cum_v:
                pts.append({"time": b["time"], "value": round(cum_pv / cum_v, 2)})
        out["series"]["vwap"] = pts

    if which in ("rsi", "all"):
        pts = []
        for i in range(14, len(closes)):
            w = closes[i - 14 : i + 1]
            g = sum(max(w[j] - w[j - 1], 0) for j in range(1, 15)) / 14
            l = sum(max(w[j - 1] - w[j], 0) for j in range(1, 15)) / 14
            v = 100.0 if l == 0 else 100 - 100 / (1 + g / l)
            pts.append({"time": times[i], "value": round(v, 1)})
        out["series"]["rsi14"] = pts

    if which in ("fib", "all"):
        w = closes[-120:] if len(closes) >= 120 else closes
        hi, lo_ = max(w), min(w)
        rng = hi - lo_
        out["levels"] += [
            {"label": f"Fib {int(r*1000)/10}%", "price": round(hi - rng * r, 2), "kind": "fib"}
            for r in (0.0, 0.236, 0.382, 0.5, 0.618, 0.786, 1.0)
        ]

    if which in ("levels", "all"):
        # Swing pivots: local extremes over a 5-bar window, clustered.
        w = bars[-120:]
        highs = [w[i]["high"] for i in range(2, len(w) - 2)
                 if w[i]["high"] == max(x["high"] for x in w[i - 2 : i + 3])]
        lows = [w[i]["low"] for i in range(2, len(w) - 2)
                if w[i]["low"] == min(x["low"] for x in w[i - 2 : i + 3])]
        last = closes[-1]
        res = sorted({round(h, 2) for h in highs if h > last})[:3]
        sup = sorted({round(l, 2) for l in lows if l < last}, reverse=True)[:3]
        out["levels"] += [{"label": "Resistance", "price": p, "kind": "res"} for p in res]
        out["levels"] += [{"label": "Support", "price": p, "kind": "sup"} for p in sup]

    return out


