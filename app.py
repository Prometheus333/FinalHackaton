@app.route("/api/tts", methods=["POST"])
def api_tts():
    """Text to speech. The API key stays on the server.

    Errors are surfaced explicitly instead of returning silent audio: a mute
    assistant with a 200 response is the hardest thing to debug.
    """
    if TTS_PROVIDER == "browser":
        return jsonify({"error": "TTS_PROVIDER=browser", "use_browser": True}), 503
    if not ELEVEN_API_KEY:
        return jsonify({"error": "ELEVENLABS_API_KEY missing from .env", "use_browser": True}), 503
    text = (request.get_json(force=True) or {}).get("text", "").strip()
    if not text:
        return jsonify({"error": "empty text"}), 400

    # flash is the fastest; if the voice does not support it, fall back.
    for model in ("eleven_flash_v2_5", "eleven_multilingual_v2"):
        try:
            r = requests.post(
                f"https://api.elevenlabs.io/v1/text-to-speech/{ELEVEN_VOICE_ID}/stream",
                params={"output_format": "mp3_44100_128"},
                headers={"xi-api-key": ELEVEN_API_KEY, "Content-Type": "application/json"},
                json={
                    "text": text[:1200],
                    "model_id": model,
                    "voice_settings": {"stability": 0.5, "similarity_boost": 0.75},
                },
                timeout=30,
                stream=True,
                verify=VERIFY_SSL,
            )
            if r.status_code == 200:
                audio = r.content  # buffered: partial streams broke playback
                if len(audio) < 500:
                    raise ValueError(f"audio too small ({len(audio)} bytes)")
                return Response(audio, mimetype="audio/mpeg",
                                headers={"Content-Length": str(len(audio))})
            detail = r.text[:400]
            app.logger.warning("TTS %s -> %s: %s", model, r.status_code, detail)
            if r.status_code in (401, 403):
                # A 401 from ElevenLabs covers several very different problems.
                # The real cause lives in detail.status; surface it verbatim.
                status = ""
                try:
                    status = ((r.json().get("detail") or {}).get("status") or "")
                except Exception:  # noqa: BLE001
                    pass
                hints = {
                    "quota_exceeded":
                        "Character quota exhausted. Check your usage at elevenlabs.io; "
                        "the plan resets monthly.",
                    "detected_unusual_activity":
                        "ElevenLabs flagged unusual activity — this is common on free "
                        "tiers behind a VPN or a corporate proxy. Free TTS is disabled "
                        "until you upgrade or contact their support.",
                    "invalid_api_key":
                        "The key is wrong or was revoked. Regenerate it at "
                        "elevenlabs.io > profile > API Keys.",
                    "missing_permissions":
                        "The key lacks the text_to_speech permission. Recreate it with "
                        "that scope enabled.",
                }
                msg = hints.get(status, f"ElevenLabs rejected the request ({r.status_code}).")
                return jsonify({"error": msg, "eleven_status": status or None,
                                "detail": detail,
                                "use_browser": TTS_PROVIDER == "auto"}), 502
            if r.status_code == 422:
                continue  # voice/model mismatch: try the next model
            return jsonify({"error": f"ElevenLabs {r.status_code}: {detail}"}), 502
        except Exception as exc:  # noqa: BLE001
            app.logger.warning("TTS %s failed: %s", model, exc)
    return jsonify({"error": f"TTS unavailable for voice {ELEVEN_VOICE_ID}",
                    "use_browser": TTS_PROVIDER == "auto"}), 502


